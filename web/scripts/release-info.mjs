// Stamp the download facts from the real release build so the page can't
// drift from the file people download. Falls back to the committed
// release.ts when no local build exists (e.g. a fresh clone or CI).
import { createHash } from 'node:crypto';
import { existsSync, readFileSync, statSync, writeFileSync } from 'node:fs';

const root = new URL('../../', import.meta.url);
const exe = process.env.RELEASE_EXE || new URL('src-tauri/target/release/quillpad.exe', root);
const pkg = JSON.parse(readFileSync(new URL('package.json', root), 'utf8'));
const out = new URL('../src/release.ts', import.meta.url);

if (!existsSync(exe)) {
  if (existsSync(out)) {
    // keep the committed facts only if they describe this version — otherwise
    // the page would publish a download link and checksum for another release
    const stamped = readFileSync(out, 'utf8').match(/"version": "([^"]+)"/)?.[1];
    if (stamped !== pkg.version) {
      console.error(`release-info: release.ts is for v${stamped} but the app is v${pkg.version} — build the app and re-run`);
      process.exit(1);
    }
    console.log(`release-info: no local exe, keeping release.ts for v${stamped}`);
    process.exit(0);
  }
  console.error('release-info: build the app first (npm run tauri build -- --no-bundle)');
  process.exit(1);
}

const version = pkg.version;
const info = {
  version,
  fileName: 'Quillpad.exe',
  url: `https://github.com/uppalasrichaitanya/Quillpad/releases/download/v${version}/Quillpad.exe`,
  releasesUrl: 'https://github.com/uppalasrichaitanya/Quillpad/releases',
  sizeBytes: statSync(exe).size,
  sha256: createHash('sha256').update(readFileSync(exe)).digest('hex'),
};
writeFileSync(
  out,
  `// generated by scripts/release-info.mjs — do not edit\nexport const RELEASE = ${JSON.stringify(info, null, 2)} as const;\n\nexport const RELEASE_MB = (RELEASE.sizeBytes / (1024 * 1024)).toFixed(0);\n`,
);
console.log(`release-info: v${info.version} ${info.sha256.slice(0, 12)}…`);
