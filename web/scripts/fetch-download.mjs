/**
 * Pre-build step: copies the freshly built app exe into public/download and
 * stamps its real size + sha256 into src/download-info.ts, so the page can
 * never serve facts that drift from the artifact. Fails loudly when the exe
 * is missing or was built without embedded assets.
 */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync, statSync, mkdirSync, copyFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.dirname(fileURLToPath(new URL(".", import.meta.url)));
const web = path.resolve(root, "..");
const exe = path.resolve(root, "../src-tauri/target/release/quillpad.exe");
const dest = path.join(web, "public", "download", "Quillpad.exe");
const infoFile = path.join(web, "src", "download-info.ts");

const bytes = readFileSync(exe);
// The asset map embeds the literal path key "index.html"; a bare
// cargo build (no custom-protocol) ships an empty asset set instead.
if (!bytes.includes(Buffer.from("index.html"))) {
  console.error(
    "quillpad.exe has no embedded asset map (index.html not found in binary).\n" +
      "Build with: npm run tauri build -- --no-bundle",
  );
  process.exit(1);
}

mkdirSync(path.dirname(dest), { recursive: true });
copyFileSync(exe, dest);

const sha256 = createHash("sha256").update(bytes).digest("hex");
const sizeBytes = statSync(exe).size;

const banner = `/**
 * Real download artifact facts. This file is generated by
 * scripts/fetch-download.mjs (runs before every build) so the page can never
 * drift from the artifact it serves. Edit the template there, not here.
 */`;
const body = `export const DOWNLOAD = {
  version: "0.1.0",
  fileName: "Quillpad.exe",
  href: "/download/Quillpad.exe",
  sizeBytes: ${sizeBytes},
  sha256: "${sha256}",
};
`;
const tail = `
export function formatBytes(bytes: number): string {
  if (bytes <= 0) return "";
  const mib = bytes / (1024 * 1024);
  return \`${"${mib.toFixed(1)}"} MB\`;
}
`;
writeFileSync(infoFile, `${banner}\n${body}\n${tail}`);

console.log(`staged ${sizeBytes} bytes, sha256 ${sha256.slice(0, 12)}...`);
